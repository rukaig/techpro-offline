export function stars(count, total = 3, size = 16) {
  let out = "";
  for (let i = 0; i < total; i += 1) {
    out += `<span class="star ${i < count ? "is-on" : ""}" aria-hidden="true">${icon(i < count ? "starFill" : "star", size)}</span>`;
  }
  return `<span class="star-row" role="img" aria-label="${count} of ${total} stars">${out}</span>`;
}

